// Builds the two document assets the Flutter WebView loads:
//
//   flutter/assets/document_viewer/viewer.js   (IIFE, self-contained)
//   flutter/assets/document_viewer/viewer.css
//
// and regenerates the browser preview from sample.md, so the harness a human
// looks at is always the renderer that ships.
//
// The assets are committed, so a Flutter checkout builds without Bun or npm.
// Re-run after changing src/ or the pinned versions in package.json:
//
//   cd flutter/tool/document_viewer && bun install && bun run build
import { build } from 'bun';
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, '..', '..', 'assets', 'document_viewer');
await mkdir(outDir, { recursive: true });

const result = await build({
  entrypoints: [join(here, 'src', 'viewer.js')],
  outdir: outDir,
  naming: 'viewer.js',
  target: 'browser',
  format: 'iife',
  minify: true,
  banner: '/* Generated by flutter/tool/document_viewer — do not edit by hand. */',
});

if (!result.success) {
  for (const message of result.logs) console.error(message);
  process.exit(1);
}

await copyFile(join(here, 'src', 'viewer.css'), join(outDir, 'viewer.css'));

const sample = JSON.stringify(await readFile(join(here, 'sample.md'), 'utf8')).replaceAll(
  '</',
  '<\\/',
);

await writeFile(
  join(here, 'preview.html'),
  `<!doctype html>
<!-- Generated by build.mjs from sample.md — open it to see the renderer the app ships. -->
<html lang="en" data-appearance="light">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Document renderer preview</title>
    <link rel="stylesheet" href="../../assets/document_viewer/viewer.css" />
  </head>
  <body>
    <article id="document" class="markdown-body" aria-busy="true"></article>
    <script type="application/json" id="sample">${sample}</script>
    <script src="../../assets/document_viewer/viewer.js"></script>
    <script>
      window.__rendered = window.gitpulseDocument.render({
        source: JSON.parse(document.getElementById('sample').textContent),
        base: 'https://github.com/owner/repo/blob/main/README.md',
        strings: { copyCode: 'Copy', copied: 'Copied', plainText: 'Text' },
      });
      window.__probe = window.__rendered.then(() => {
        const root = document.getElementById('document');
        const all = (selector) => Array.from(root.querySelectorAll(selector));
        const style = (selector) => (selector ? getComputedStyle(root.querySelector(selector)) : null);
        return {
          headings: all('h1, h2, h3').map((node) => node.tagName + ':' + node.textContent.trim()),
          alerts: all('.markdown-alert').map((node) => node.className),
          codeLanguages: all('.code-block-language').map((node) => node.textContent),
          tables: all('table').length,
          tasks: all('input[type="checkbox"]').length,
          scripts: all('script').length,
          iframes: all('iframe').length,
          styles: all('style').length,
          javascriptLinks: all('a[href^="javascript:"]').length,
          dataImages: all('img[src^="data:"]').length,
          fontSizes: {
            body: style('.markdown-body')?.fontSize,
            h1: style('h1')?.fontSize,
            h2: style('h2')?.fontSize,
            code: style('.code-block code')?.fontSize,
            lineHeight: style('.markdown-body')?.lineHeight,
          },
        };
      });
    </script>
  </body>
</html>
`,
);

console.log(`wrote ${outDir} and preview.html`);
